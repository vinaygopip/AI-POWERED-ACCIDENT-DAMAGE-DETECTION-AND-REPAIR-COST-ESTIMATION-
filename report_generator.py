import os
from datetime import datetime
import config

try:
    from reportlab.lib.pagesizes import letter
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image, HRFlowable
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib import colors
    REPORTLAB_AVAILABLE = True
except ImportError:
    REPORTLAB_AVAILABLE = False


def generate_pdf_report(report_data, output_filepath):
    """
    Module 6: Report Generation (AI Inspection Report PDF Download)
    """
    os.makedirs(os.path.dirname(output_filepath), exist_ok=True)

    if not REPORTLAB_AVAILABLE:
        # Fallback simple text report if ReportLab fails
        with open(output_filepath, 'w') as f:
            f.write(f"ACCIDENT DAMAGE INSPECTION REPORT\n")
            f.write(f"Report ID: {report_data.get('report_id')}\n")
            f.write(f"Total Estimated Cost: Rs. {report_data.get('summary', {}).get('total_estimated_cost', 0)}\n")
        return output_filepath

    doc = SimpleDocTemplate(
        output_filepath,
        pagesize=letter,
        rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36
    )

    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#0F172A'),
        alignment=0
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=12,
        textColor=colors.HexColor('#64748B')
    )

    section_header = ParagraphStyle(
        'SectionHeader',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=12,
        leading=16,
        textColor=colors.HexColor('#1E293B'),
        spaceBefore=10,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#334155')
    )

    bold_body = ParagraphStyle(
        'BoldBody',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#0F172A')
    )

    elements = []

    # Title & Header
    elements.append(Paragraph("AI VEHICLE INSPECTION & DAMAGE REPORT", title_style))
    elements.append(Paragraph(f"Generated by Automated YOLOv8 AI Detection Engine • Date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", subtitle_style))
    elements.append(Spacer(1, 10))
    elements.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor('#3B82F6'), spaceAfter=15))

    # Meta Table: Vehicle & Owner Info
    veh = report_data.get('vehicle', {})
    user = report_data.get('user', {})
    
    owner_info_data = [
        [Paragraph("<b>Report ID:</b>", body_style), Paragraph(str(report_data.get('report_id', 'N/A')), bold_body),
         Paragraph("<b>Vehicle Brand/Model:</b>", body_style), Paragraph(f"{veh.get('car_brand', 'N/A')} {veh.get('model', '')}", bold_body)],
        [Paragraph("<b>Owner Name:</b>", body_style), Paragraph(str(user.get('name', 'N/A')), body_style),
         Paragraph("<b>VIN / Reg No:</b>", body_style), Paragraph(str(veh.get('vin_number', 'N/A')), body_style)],
        [Paragraph("<b>Contact:</b>", body_style), Paragraph(str(user.get('contact_number', 'N/A')), body_style),
         Paragraph("<b>Insurance Provider:</b>", body_style), Paragraph(str(veh.get('insurance_provider', 'N/A')), body_style)],
        [Paragraph("<b>Email:</b>", body_style), Paragraph(str(user.get('email', 'N/A')), body_style),
         Paragraph("<b>Policy Number:</b>", body_style), Paragraph(str(veh.get('policy_number', 'N/A')), body_style)]
    ]

    meta_table = Table(owner_info_data, colWidths=[90, 180, 110, 160])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#E2E8F0')),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 15))

    # AI Detection & Severity Breakdown Header
    elements.append(Paragraph("AI Damage Detection & Severity Breakdown", section_header))

    detections = report_data.get('detections', [])
    det_table_data = [
        [Paragraph("<b>#</b>", bold_body),
         Paragraph("<b>Damaged Part</b>", bold_body),
         Paragraph("<b>Damage Type</b>", bold_body),
         Paragraph("<b>Severity Level</b>", bold_body),
         Paragraph("<b>Confidence</b>", bold_body),
         Paragraph("<b>Part Cost (INR)</b>", bold_body)]
    ]

    for idx, d in enumerate(detections, 1):
        sev = d.get('severity', 'Minor')
        sev_color = '#EF4444' if sev == 'Severe' else ('#F59E0B' if sev == 'Moderate' else '#10B981')
        det_table_data.append([
            Paragraph(str(idx), body_style),
            Paragraph(str(d.get('part_name', 'N/A')), bold_body),
            Paragraph(str(d.get('damage_type', 'N/A')), body_style),
            Paragraph(f"<font color='{sev_color}'><b>{sev}</b></font>", body_style),
            Paragraph(f"{d.get('confidence', 0)}%", body_style),
            Paragraph(f"Rs. {d.get('effective_part_cost', d.get('part_cost', 0)):,.2f}", body_style)
        ])

    if len(det_table_data) == 1:
        det_table_data.append([Paragraph("1", body_style), Paragraph("No severe damage detected", body_style), Paragraph("-", body_style), Paragraph("Minor", body_style), Paragraph("100%", body_style), Paragraph("Rs. 0.00", body_style)])

    det_table = Table(det_table_data, colWidths=[30, 110, 110, 100, 80, 110])
    det_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#F1F5F9')),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#CBD5E1')),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]))
    elements.append(det_table)
    elements.append(Spacer(1, 15))

    # Cost Estimation Summary
    elements.append(Paragraph("Cost Estimation & Repair Schedule", section_header))
    summary = report_data.get('summary', {})

    cost_data = [
        [Paragraph("Total Parts Cost:", body_style), Paragraph(f"Rs. {summary.get('total_parts_cost', 0):,.2f}", body_style)],
        [Paragraph("Total Labour Cost:", body_style), Paragraph(f"Rs. {summary.get('total_labour_cost', 0):,.2f}", body_style)],
        [Paragraph("Total Paint & Refinishing Cost:", body_style), Paragraph(f"Rs. {summary.get('total_paint_cost', 0):,.2f}", body_style)],
        [Paragraph(f"Applicable Tax ({summary.get('tax_rate', 18)}% GST):", body_style), Paragraph(f"Rs. {summary.get('tax_amount', 0):,.2f}", body_style)],
        [Paragraph("<b>TOTAL ESTIMATED REPAIR COST:</b>", bold_body), Paragraph(f"<b>Rs. {summary.get('total_estimated_cost', 0):,.2f}</b>", bold_body)],
        [Paragraph("Estimated Repair Duration:", body_style), Paragraph(f"{summary.get('total_repair_hours', 0)} Hours (~{summary.get('estimated_days', 1)} Business Days)", bold_body)]
    ]

    cost_table = Table(cost_data, colWidths=[240, 300])
    cost_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 4), (-1, 4), colors.HexColor('#DBEAFE')),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#CBD5E1')),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(cost_table)
    elements.append(Spacer(1, 20))

    # Disclaimer & Signature
    disclaimer_text = "<b>Notice:</b> This inspection report is automatically generated using YOLOv8 AI object recognition algorithms. Final claim settlement values remain subject to physical verification by authorized insurance assessors."
    elements.append(Paragraph(disclaimer_text, subtitle_style))
    elements.append(Spacer(1, 15))

    doc.build(elements)
    return output_filepath
